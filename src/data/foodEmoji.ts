/**
 * 部分一致ルール(上から順に評価)。
 * 追加するときは 433 件の名前と衝突しないことを確認してから。
 */
const RULES: readonly (readonly [string, string])[] = [
  ['まい', '🍚'], // あかまい・くろまい・げんまい・うるちまい…
  ['こめ', '🍚'], // もちごめ・こめこうじ…
  ['むぎ', '🌾'], // こむぎ・おおむぎ・はとむぎ…
  ['まめ', '🫘'], // あずき系を除く豆類
  ['いも', '🍠'], // じゃがいもは EXACT が先勝ち
  ['にく', '🥩'], // ぎゅうにく・ぶたにく…(「こんにゃく」は「にく」を含まない)
];

/** 食材名から仮ビジュアルの絵文字を引く。なければ null(タイル側で頭文字表示) */
export function getFoodEmoji(name: string): string | null {
  const exact = EXACT[name];
  if (exact !== undefined) return exact;
  for (const [pattern, emoji] of RULES) {
    if (name.includes(pattern)) return emoji;
  }
  return null;
}
